// ---------------------------------------------------------------------------
// Regularized incomplete gamma (upper tail) and the chi-square survival fn.

var lanczosG = [9]float64{
	0.99999999999980993,
	676.5203681218851,
	-1259.1392167224028,
	771.32342877765313,
	-176.61502916214059,
	12.507343278686905,
	-0.13857109526572012,
	9.9843695780195716e-6,
	1.5056327351493116e-7,
}

func lnGamma(x float64) float64 {
	if x < 0.5 {
		// Reflection formula: Gamma(x)Gamma(1-x) = pi / sin(pi x)
		return math.Log(math.Pi/math.Sin(math.Pi*x)) - lnGamma(1-x)
	}
	x -= 1
	a := lanczosG[0]
	t := x + 7.5
	for i := 1; i < 9; i++ {
		a += lanczosG[i] / (x + float64(i))
	}
	return 0.5*math.Log(2*math.Pi) + (x+0.5)*math.Log(t) - t + math.Log(a)
}

// gammaQ returns the regularized UPPER incomplete gamma function
// Q(a, x) = Gamma(a, x) / Gamma(a), for a > 0 and x >= 0.
func gammaQ(a, x float64) float64 {
	if x < 0 || a <= 0 {
		return math.NaN()
	}
	if x == 0 {
		return 1
	}
	if x < a+1 {
		// Series for the LOWER function, then complement.
		ap := a
		sum := 1.0 / a
		del := sum
		for i := 0; i < 500; i++ {
			ap++
			del *= x / ap
			sum += del
			if math.Abs(del) < math.Abs(sum)*1e-15 {
				break
			}
		}
		return 1 - sum*math.Exp(-x+a*math.Log(x)-lnGamma(a))
	}
	// Continued fraction (modified Lentz) for the UPPER function directly.
	b := x + 1 - a
	c := 1e300
	d := 1 / b
	h := d
	for i := 1; i < 500; i++ {
		an := -float64(i) * (float64(i) - a)
		b += 2
		d = an*d + b
		if math.Abs(d) < 1e-300 {
			d = 1e-300
		}
		c = b + an/c
		if math.Abs(c) < 1e-300 {
			c = 1e-300
		}
		d = 1 / d
		del := d * c
		h *= del
		if math.Abs(del-1) < 1e-15 {
			break
		}
	}
	return math.Exp(-x+a*math.Log(x)-lnGamma(a)) * h
}

// chiSquareSF is the chi-square survival function P(X > x) with df degrees
// of freedom: Q(df/2, x/2).
func chiSquareSF(df int, x float64) float64 {
	if df <= 0 || x <= 0 {
		return 1
	}
	p := gammaQ(float64(df)/2, x/2)
	if math.IsNaN(p) {
		return 1
	}
	if p < 0 {
		return 0
	}
	if p > 1 {
		return 1
	}
	return p
}

// ---------------------------------------------------------------------------
// Omnibus Pearson chi-square over k arms (converted / not-converted).

// ChiSquareResult is the omnibus test outcome.
type ChiSquareResult struct {
	Stat      float64
	DF        int
	PValue    float64
	UsedYates bool
	// SmallCells is true when any expected cell count is below 5: the
	// chi-square approximation is unreliable and (for two arms) the Fisher
	// exact fallback applies instead.
	SmallCells bool
}

// chiSquareOmnibus computes the Pearson chi-square over the k x 2 table of
// conversions vs non-conversions. Yates continuity correction is applied
// only for exactly two arms (df=1), where it is well-defined.
func chiSquareOmnibus(exposures, conversions []int64) ChiSquareResult {
	k := len(exposures)
	res := ChiSquareResult{DF: k - 1}
	if k < 2 {
		return res
	}
	var n, conv int64
	for i := range exposures {
		n += exposures[i]
		conv += conversions[i]
	}
	if n == 0 {
		res.PValue = 1
		return res
	}
	overall := float64(conv) / float64(n)
	res.UsedYates = k == 2
	var chi float64
	for i := range exposures {
		if exposures[i] == 0 {
			continue
		}
		for _, observed := range []int64{conversions[i], exposures[i] - conversions[i]} {
			expected := float64(exposures[i]) * map[bool]float64{true: overall, false: 1 - overall}[observed == conversions[i]]
			if expected > 0 && expected < 5 {
				res.SmallCells = true
			}
			if expected <= 0 {
				continue
			}
			d := math.Abs(float64(observed) - expected)
			if res.UsedYates {
				d = math.Max(0, d-0.5)
			}
			chi += d * d / expected
		}
	}
	res.Stat = chi
	res.PValue = chiSquareSF(res.DF, chi)
	return res
}

// ---------------------------------------------------------------------------
// Fisher exact test, 2x2, two-sided.

func lnFact(n int64) float64 {
	return lnGamma(float64(n + 1))
}

// fisherExact2x2TwoSided computes the two-sided Fisher exact p-value for
// the 2x2 table [[a, b], [c, d]] (converted/not for two arms), summing the
// probabilities of all tables (with fixed margins) at most as probable as
// the observed one.
func fisherExact2x2TwoSided(a, b, c, d int64) float64 {
	if a < 0 || b < 0 || c < 0 || d < 0 {
		return math.NaN()
	}
	r1 := a + b
	r2 := c + d
	c1 := a + c
	n := r1 + r2
	if n == 0 {
		return 1
	}
	// P(x) = C(r1,x) * C(r2,c1-x) / C(n,c1)
	lnDenom := lnFact(r1) + lnFact(r2) + lnFact(c1) + lnFact(n-c1) - lnFact(n)
	prob := func(x int64) float64 {
		return math.Exp(lnDenom - lnFact(x) - lnFact(r1-x) - lnFact(c1-x) - lnFact(r2-c1+x))
	}
	pObs := prob(a)
	var sum float64
	lo := int64(0)
	if r1+c1-n > lo {
		lo = r1 + c1 - n // d = n - r1 - c1 + x >= 0
	}
	hi := r1
	if c1 < hi {
		hi = c1 // c = c1 - x >= 0
	}
	for x := lo; x <= hi; x++ {
		p := prob(x)
		if p <= pObs*(1+1e-9) {
			sum += p
		}
	}
	if sum > 1 {
		sum = 1
	}
	return sum
}

// ---------------------------------------------------------------------------
// Wilson score interval and Newcombe hybrid-score difference interval.

// wilsonInterval returns the Wilson score interval for k successes in n
// trials at the given z (1.96 for 95%).
func wilsonInterval(k, n int64, z float64) (low, high float64) {
	if n == 0 {
		return 0, 0
	}
	// Degenerate cases are exact: the analytic bounds collapse to 0 / 1 and
	// floating point leaves ~1e-19 residue instead.
	if k <= 0 {
		return 0, clamp01(wilsonHigh(0, n, z))
	}
	if k >= n {
		return clamp01(wilsonLow(n, n, z)), 1
	}
	low, high = wilsonLow(k, n, z), wilsonHigh(k, n, z)
	return clamp01(low), clamp01(high)
}

func wilsonLow(k, n int64, z float64) float64 {
	fn, z2 := float64(n), z*z
	p := float64(k) / fn
	return (p + z2/(2*fn) - z*math.Sqrt(p*(1-p)/fn+z2/(4*fn*fn))) / (1 + z2/fn)
}

func wilsonHigh(k, n int64, z float64) float64 {
	fn, z2 := float64(n), z*z
	p := float64(k) / fn
	return (p + z2/(2*fn) + z*math.Sqrt(p*(1-p)/fn+z2/(4*fn*fn))) / (1 + z2/fn)
}

// newcombeDifferenceCI returns Newcombe's hybrid-score confidence interval
// (method 10, "square and add") for p2 - p1, from each proportion's Wilson
// bounds.
func newcombeDifferenceCI(k1, n1, k2, n2 int64, z float64) (low, high float64) {
	if n1 == 0 || n2 == 0 {
		return 0, 0
	}
	l1, u1 := wilsonInterval(k1, n1, z)
	l2, u2 := wilsonInterval(k2, n2, z)
	p1 := float64(k1) / float64(n1)
	p2 := float64(k2) / float64(n2)
	diff := p2 - p1
	low = diff - math.Sqrt((l2-p2)*(l2-p2)+(u1-p1)*(u1-p1))
	high = diff + math.Sqrt((u2-p2)*(u2-p2)+(l1-p1)*(l1-p1))
	return
}

func clamp01(v float64) float64 {
	if v < 0 {
		return 0
	}
	if v > 1 {
		return 1
	}
	return v
}

// ---------------------------------------------------------------------------
// Holm correction across the pairwise-vs-control family.

// holmAdjusted returns the Holm step-down adjusted p-values, preserving the
// input order. adjusted[i] <= alpha is the rejection criterion.
func holmAdjusted(p []float64) []float64 {
	m := len(p)
	order := make([]int, m)
	for i := range order {
		order[i] = i
	}
	// insertion sort by p ascending (m is the arm count: tiny)
	for i := 1; i < m; i++ {
		for j := i; j > 0 && p[order[j]] < p[order[j-1]]; j-- {
			order[j], order[j-1] = order[j-1], order[j]
		}
	}
	adj := make([]float64, m)
	running := 0.0
	for rank, idx := range order {
		a := float64(m-rank) * p[idx]
		if a > 1 {
			a = 1
		}
		if a > running {
			running = a
		}
		adj[idx] = running
	}
	return adj
}

// ---------------------------------------------------------------------------
// Sample ratio mismatch: goodness-of-fit of observed arm counts against the
// declared allocation, alpha=0.001 by decision.

// srmGoodnessOfFit returns the chi-square GoF statistic and p-value of the
// observed per-arm counts against the declared allocation weights (which
// are normalized internally). Uniform weights are assumed when every weight
// is zero.
func srmGoodnessOfFit(counts []int64, weights []float64) (stat, p float64) {
	k := len(counts)
	if k < 2 {
		return 0, 1
	}
	var total int64
	var wsum float64
	for i := range counts {
		total += counts[i]
		wsum += weights[i]
	}
	if total == 0 {
		return 0, 1
	}
	if wsum <= 0 {
		wsum = float64(k)
		for i := range weights {
			weights[i] = 1
		}
	}
	var chi float64
	for i := range counts {
		e := float64(total) * weights[i] / wsum
		if e <= 0 {
			continue
		}
		d := float64(counts[i]) - e
		chi += d * d / e
	}
	return chi, chiSquareSF(k-1, chi)
}

// ---------------------------------------------------------------------------
// MDE-based per-arm sample size recommendation (design time).

// sampleSizePerArm returns the per-arm n needed for baseline rate p1, an
// absolute lift delta, two-sided alpha and the given power (normal
// approximation to the two-proportion test). Returned n is ceil'ed and
// floored at 2.
// SampleSizePerArm is the exported design-time helper (the /api/v1/
// experiments/sample-size endpoint); the fixtures pin it against
// scipy-derived goldens.
func SampleSizePerArm(p1, delta, alpha, power float64) int64 {
	return sampleSizePerArm(p1, delta, alpha, power)
}

func sampleSizePerArm(p1, delta, alpha, power float64) int64 {
	if p1 <= 0 || p1 >= 1 || delta <= 0 || p1+delta >= 1 {
		return 0
	}
	zA := inverseNormalCDF(1 - alpha/2)
	zB := inverseNormalCDF(power)
	p2 := p1 + delta
	pBar := (p1 + p2) / 2
	numer := zA*math.Sqrt(2*pBar*(1-pBar)) + zB*math.Sqrt(p1*(1-p1)+p2*(1-p2))
	n := numer * numer / (delta * delta)
	return int64(math.Ceil(n))
}

// inverseNormalCDF is the Acklam approximation of the standard normal
// quantile (|relative error| < 1.15e-9), refined with one Halley step.
func inverseNormalCDF(p float64) float64 {
	if p <= 0 || p >= 1 {
		return math.NaN()
	}
	a := []float64{-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02, 1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00}
	b := []float64{-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02, 6.680131188771972e+01, -1.328068155288572e+01}
	c := []float64{-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00, -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00}
	d := []float64{7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e+00, 3.754408661907416e+00}
	pLow := 0.02425
	var x float64
	if p < pLow {
		q := math.Sqrt(-2 * math.Log(p))
		x = (((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q + c[5]) / ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q + 1)
	} else if p <= 1-pLow {
		q := p - 0.5
		r := q * q
		x = (((((a[0]*r+a[1])*r+a[2])*r+a[3])*r+a[4])*r + a[5]) * q / (((((b[0]*r+b[1])*r+b[2])*r+b[3])*r+b[4])*r + 1)
	} else {
		q := math.Sqrt(-2 * math.Log(1-p))
		x = -(((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q + c[5]) / ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q + 1)
	}
	// One Halley refinement.
	e := normalCDF(x) - p
	u := e * math.Sqrt(2*math.Pi) * math.Exp(x*x/2)
	x -= u / (1 + x*u/2)
	return x
}

func normalCDF(x float64) float64 {
	return 0.5 * (1 + math.Erf(x/math.Sqrt2))
}
