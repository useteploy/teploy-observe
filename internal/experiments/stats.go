// Pure statistics for O09 experiment analysis (decided defaults 2026-09-23,
// DELEGATED_DECISIONS section 4): fixed-horizon two-sided alpha=0.05 Pearson
// chi-square with Yates correction for two arms and Fisher exact fallback
// when any expected cell count is below 5, Holm-corrected pairwise winner
// claims against control, sample-ratio-mismatch detection as a chi-square
// goodness-of-fit against the declared allocation at alpha=0.001, Wilson
// score intervals per arm and Newcombe hybrid-score intervals for
// differences, and an MDE-based per-arm sample size recommendation.
//
// Everything here is a pure function so the golden tables (generated by an
// independent implementation - scipy via the fixture script) and the
// simulation fixtures pin exact behavior.

import "math"

